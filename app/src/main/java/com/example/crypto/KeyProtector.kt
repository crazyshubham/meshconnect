package com.example.crypto

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * Protects private key material and local storage master keys using Android Keystore
 * where supported by the device hardware/OS.
 */
interface KeyProtector {
    val isHardwareKeystoreActive: Boolean
    fun seal(plaintext: ByteArray, associatedData: ByteArray = ByteArray(0)): ByteArray
    fun unseal(sealedBlob: ByteArray, associatedData: ByteArray = ByteArray(0)): ByteArray
    fun deleteMasterKey()
}

class AndroidKeystoreProtector(
    private val keyAlias: String = "meshconnect_master_aes_wrap_v1"
) : KeyProtector {

    override val isHardwareKeystoreActive: Boolean
        get() = try {
            KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
            true
        } catch (_: Exception) {
            false
        }

    private fun getOrCreateMasterKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        val existing = keyStore.getKey(keyAlias, null) as? SecretKey
        if (existing != null) return existing

        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            ANDROID_KEYSTORE
        )
        val spec = KeyGenParameterSpec.Builder(
            keyAlias,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
            .build()
        keyGenerator.init(spec)
        return keyGenerator.generateKey()
    }

    override fun seal(plaintext: ByteArray, associatedData: ByteArray): ByteArray {
        val key = getOrCreateMasterKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)
        if (associatedData.isNotEmpty()) {
            cipher.updateAAD(associatedData)
        }
        val iv = cipher.iv // 12 bytes generated by Keystore
        val ciphertext = cipher.doFinal(plaintext)
        return ByteArray(1 + iv.size + ciphertext.size).apply {
            this[0] = iv.size.toByte()
            System.arraycopy(iv, 0, this, 1, iv.size)
            System.arraycopy(ciphertext, 0, this, 1 + iv.size, ciphertext.size)
        }
    }

    override fun unseal(sealedBlob: ByteArray, associatedData: ByteArray): ByteArray {
        require(sealedBlob.size > 13) { "Invalid sealed key blob" }
        val ivLen = sealedBlob[0].toInt() and 0xFF
        require(ivLen == 12 && sealedBlob.size > 1 + ivLen) { "Invalid GCM IV length" }
        val iv = sealedBlob.copyOfRange(1, 1 + ivLen)
        val ciphertext = sealedBlob.copyOfRange(1 + ivLen, sealedBlob.size)

        val key = getOrCreateMasterKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(GCM_TAG_BITS, iv))
        if (associatedData.isNotEmpty()) {
            cipher.updateAAD(associatedData)
        }
        return cipher.doFinal(ciphertext)
    }

    override fun deleteMasterKey() {
        runCatching {
            val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
            if (keyStore.containsAlias(keyAlias)) {
                keyStore.deleteEntry(keyAlias)
            }
        }
    }

    companion object {
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_TAG_BITS = 128
    }
}

/**
 * Ephemeral in-memory KeyProtector exclusively for JVM/Robolectric unit tests where
 * AndroidKeyStore is absent. Never used in production Application wiring.
 */
class EphemeralTestKeyProtector : KeyProtector {
    private val random = SecureRandom()
    private var keyBytes = ByteArray(32).also { random.nextBytes(it) }
    override val isHardwareKeystoreActive: Boolean = false

    override fun seal(plaintext: ByteArray, associatedData: ByteArray): ByteArray {
        val iv = ByteArray(12).also { random.nextBytes(it) }
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, SecretKeySpec(keyBytes, "AES"), GCMParameterSpec(128, iv))
        if (associatedData.isNotEmpty()) cipher.updateAAD(associatedData)
        val ct = cipher.doFinal(plaintext)
        return byteArrayOf(12.toByte()) + iv + ct
    }

    override fun unseal(sealedBlob: ByteArray, associatedData: ByteArray): ByteArray {
        val ivLen = sealedBlob[0].toInt() and 0xFF
        val iv = sealedBlob.copyOfRange(1, 1 + ivLen)
        val ct = sealedBlob.copyOfRange(1 + ivLen, sealedBlob.size)
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, SecretKeySpec(keyBytes, "AES"), GCMParameterSpec(128, iv))
        if (associatedData.isNotEmpty()) cipher.updateAAD(associatedData)
        return cipher.doFinal(ct)
    }

    override fun deleteMasterKey() {
        keyBytes.fill(0)
    }
}
